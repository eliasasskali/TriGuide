import Foundation

public extension Localizables {
    enum Units {
        // MARK: - Short symbols (universal, not localized)

        // MARK: - Distance
        public static let kmSymbol = "km"
        public static let miSymbol = "mi"
        public static let mSymbol = "m"
        public static let ydSymbol = "yd"

        // MARK: - Speed
        public static let kmhSymbol = "km/h"
        public static let mphSymbol = "mph"
        public static let msSymbol = "m/s"
        public static let ydsSymbol = "yd/s"

        // MARK: - Pace
        public static let minPerKmSymbol = "min/km"
        public static let minPerMileSymbol = "min/mi"
        public static let minPer100mSymbol = "min/100m"
        public static let minPer100ydSymbol = "min/100yd"

        // MARK: - Time
        public static let hourSymbol = "h"
        public static let minuteSymbol = "min"
        public static let secondSymbol = "s"

        // MARK: - Weight/Volume
        public static let kgSymbol = "kg"
        public static let gSymbol = "g"
        public static let mgSymbol = "mg"
        public static let mlSymbol = "ml"

        // MARK: - Temperature
        public static let celsiusSymbol = "°C"
    }
}
