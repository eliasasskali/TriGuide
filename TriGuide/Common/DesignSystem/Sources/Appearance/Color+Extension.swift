import SwiftUI

public extension Color {
    enum Primary {
        // #FEFEFE
        public static let white = Color("PrimaryWhite", bundle: .module)
    }

    enum Background {
        // #EFEFEF
        public static let lightGray = Color("LightGray", bundle: .module)

        // #DCDCDC
        public static let gray = Color("Gray", bundle: .module)
    }
}
